"use client";

import { useState } from "react";
import { motion } from "framer-motion";
import { Pencil, RefreshCw, Send, Sparkles, X } from "lucide-react";
import { Badge } from "@/components/ui/badge";
import { Button } from "@/components/ui/button";
import { Card } from "@/components/ui/card";
import { Spinner } from "@/components/ui/spinner";
import { Textarea } from "@/components/ui/input";
import { ShareButton } from "@/components/growth/share-menu";
import { Attribution, ShareNudge } from "@/components/growth/attribution";
import { cn } from "@/lib/cn";

export function GeneratedCard({
  kindLabel,
  text,
  loading,
  onInsert,
  onRegenerate,
  onClose,
  onSave,
}: {
  kindLabel: string;
  text: string;
  loading: boolean;
  onInsert: () => void;
  onRegenerate: () => void;
  onClose: () => void;
  onSave: (text: string) => void;
}) {
  const [editing, setEditing] = useState(false);
  const [editText, setEditText] = useState(text);
  const [inserted, setInserted] = useState(false);
  const [nudgeGone, setNudgeGone] = useState(false);

  const startEdit = () => {
    setEditText(text);
    setEditing(true);
  };
  const saveEdit = () => {
    onSave(editText);
    setEditing(false);
  };
  const handleInsert = () => {
    onInsert();
    setInserted(true);
  };

  return (
    <motion.div
      initial={{ opacity: 0, y: 12 }}
      animate={{ opacity: 1, y: 0 }}
      exit={{ opacity: 0, y: 8 }}
      transition={{ duration: 0.2, ease: "easeOut" }}
    >
      <Card className="border-cx-purple/25 bg-gradient-to-b from-cx-purpleLight/50 to-white p-4">
        <div className="flex items-center gap-2">
          <span className="flex h-7 w-7 items-center justify-center rounded-lg bg-cx-purpleLight text-cx-purple">
            <Sparkles size={15} />
          </span>
          <p className="text-sm font-semibold text-slate-800">Generated by Client X</p>
          <Badge tone="purple" className="ml-1">
            {kindLabel}
          </Badge>
          <button
            onClick={onClose}
            className="ml-auto rounded-lg p-1.5 text-slate-400 hover:bg-white/60 hover:text-slate-600"
            aria-label="Discard generated text"
          >
            <X size={16} />
          </button>
        </div>

        <div className={cn("mt-3", loading && "flex items-center gap-2")}>
          {loading ? (
            <>
              <Spinner />
              <p className="text-sm text-slate-500">Client X is writing…</p>
            </>
          ) : editing ? (
            <Textarea
              value={editText}
              onChange={(e) => setEditText(e.target.value)}
              className="text-sm"
              autoFocus
            />
          ) : (
            <p className="whitespace-pre-wrap break-words text-sm leading-relaxed text-slate-800">
              {text}
            </p>
          )}
        </div>

        <div className="mt-3 flex flex-wrap items-center gap-2">
          {editing ? (
            <>
              <Button size="sm" variant="primary-orange" onClick={saveEdit}>
                Save
              </Button>
              <Button size="sm" variant="ghost" onClick={() => setEditing(false)}>
                Cancel
              </Button>
            </>
          ) : (
            <>
              <Button
                size="sm"
                variant="primary-orange"
                icon={<Send size={14} />}
                onClick={handleInsert}
                disabled={loading || !text.trim()}
              >
                Insert
              </Button>
              <Button
                size="sm"
                variant="secondary"
                icon={<RefreshCw size={14} />}
                onClick={onRegenerate}
                disabled={loading}
              >
                Regenerate
              </Button>
              <Button
                size="sm"
                variant="ghost"
                icon={<Pencil size={14} />}
                onClick={startEdit}
                disabled={loading}
              >
                Edit
              </Button>
              {!loading && text.trim() && (
                <ShareButton
                  kind="output"
                  title={text.slice(0, 80)}
                  sharePath={`/share/output/output?text=${encodeURIComponent(text)}&label=${encodeURIComponent(kindLabel)}`}
                />
              )}
            </>
          )}
        </div>
        {inserted && !nudgeGone && (
          <div className="mt-3" onClick={() => setNudgeGone(true)}>
            <ShareNudge text="Love this reply?" />
          </div>
        )}
        <Attribution className="mt-3" />
      </Card>
    </motion.div>
  );
}
